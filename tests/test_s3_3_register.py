"""KP/P3/S3.3 — the register, T1's third sentence (contracts.md §7, Amendment 36; docs/wow/60 ST-2, ST-4).

`scripts/build-register.py` writes `REGISTER.md` at the project checkout's root: one row per effort from its `STATUS.md`
frontmatter, in the order the efforts are given — `offices.yaml`'s, as the daemon hands them over — and the same STATUS
files give the same bytes: it holds no time of its own. The daemon's half — the efforts in `offices.yaml`'s order, and
`register.fresh` after the commit that follows — is OperationsOnTheOfficeSpec's.
"""
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest

ROOT = Path(__file__).resolve().parents[1]

KP = """---
effort: KP — Keporkak: the agentic coding platform
repo_home: project (~/Dev/keporkak/project)
code_home: [keporkak (~/Dev/keporkak/keporkak)]
state: "P3 — eyes and hands"
phase: "P3 · S3.3 in flight"
next: "the coder of S3.3 | the reviewer"
blocked_on: []
gates: []
updated: 2026-11-22
stream: dev
lane: coding
---

# KP — status
"""

TOY = """---
effort: TOY — the toy project
repo_home: project (~/Dev/keporkak/project/toy)
code_home: [kp-toy (~/Dev/keporkak/kp-toy)]
state: "S0.1 exited"
phase: "P0 · S0.1 exited"
next: "nobody"
blocked_on: []
gates: []
updated: 2026-11-14
stream: dev
lane: coding
---

# TOY — status
"""

HEADER = """# Register

Generated by `scripts/build-register.py` from each effort's `STATUS.md` frontmatter (docs/wow/60 ST-2, ST-4). Do not edit it: edit STATUS.

| effort | state | phase | next | blocked_on | gates | updated | stream | lane | repo_home | code_home |
|---|---|---|---|---|---|---|---|---|---|---|
"""

KP_ROW = ("| [KP](STATUS.md) — Keporkak: the agentic coding platform | P3 — eyes and hands | P3 · S3.3 in flight | the coder of S3.3 \\| the reviewer "
          "| [] | [] | 2026-11-22 | dev | coding | project (~/Dev/keporkak/project) | [keporkak (~/Dev/keporkak/keporkak)] |\n")
TOY_ROW = ("| [TOY](toy/STATUS.md) — the toy project | S0.1 exited | P0 · S0.1 exited | nobody "
           "| [] | [] | 2026-11-14 | dev | coding | project (~/Dev/keporkak/project/toy) | [kp-toy (~/Dev/keporkak/kp-toy)] |\n")


class RegisterTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory(dir=ROOT / "build")
        self.addCleanup(self.temp.cleanup)
        self.project = Path(self.temp.name)
        (self.project / "STATUS.md").write_text(KP)
        (self.project / "toy").mkdir()
        (self.project / "toy" / "STATUS.md").write_text(TOY)

    def build(self, *efforts):
        args = [arg for effort in efforts for arg in ("--effort", effort)]
        return subprocess.run([sys.executable, "scripts/build-register.py", "--project", str(self.project), *args], cwd=ROOT, text=True, capture_output=True)

    def test_one_effort_is_one_row_from_its_status_frontmatter(self):
        result = self.build("KP=.")

        self.assertEqual((result.returncode, result.stderr), (0, ""))
        self.assertEqual((self.project / "REGISTER.md").read_text(), HEADER + KP_ROW)

    def test_two_efforts_are_two_rows_in_the_order_given(self):
        result = self.build("TOY=toy", "KP=.")

        self.assertEqual((result.returncode, result.stderr), (0, ""))
        self.assertEqual((self.project / "REGISTER.md").read_text(), HEADER + TOY_ROW + KP_ROW)

    def test_a_status_that_lacks_a_field_of_st_2_gives_an_empty_cell_and_says_which_field_of_which_file_and_the_register_is_still_written(self):
        # S3.11 T7 (Collite/keporkak#65, 3): a missing field is said, not only left empty.
        (self.project / "toy" / "STATUS.md").write_text(TOY.replace("gates: []\n", "").replace("lane: coding\n", ""))

        result = self.build("TOY=toy", "KP=.")

        self.assertEqual((result.returncode, result.stderr), (0, ""))
        self.assertEqual(result.stdout.splitlines(), [
            "toy/STATUS.md: its frontmatter has no field gates: the cell is empty",
            "toy/STATUS.md: its frontmatter has no field lane: the cell is empty",
        ])
        self.assertIn("| [TOY](toy/STATUS.md)", (self.project / "REGISTER.md").read_text())

    def test_the_same_status_files_give_the_same_bytes(self):
        self.build("KP=.", "TOY=toy")
        first = (self.project / "REGISTER.md").read_bytes()

        self.build("KP=.", "TOY=toy")

        self.assertEqual((self.project / "REGISTER.md").read_bytes(), first)


if __name__ == "__main__":
    unittest.main()
