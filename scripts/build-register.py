#!/usr/bin/env python3
"""Rebuild REGISTER.md at the project checkout's root (docs/wow/60 ST-2, ST-4; contracts.md §7, Amendment 36).

One row per effort from its STATUS.md frontmatter, in the order the efforts are given — `pool/offices.yaml`'s, as the
daemon's `register.rebuild` hands them over — each with the folder its STATUS.md is in, relative to the checkout. The
same STATUS files give the same file, byte for byte: it holds no time of its own. The standard library only: the
daemon runs it with the office's `python3`.

Usage: python3 scripts/build-register.py --project DIR --effort KP=. --effort TOY=toy
Exit: 0 written · 1 an effort's STATUS.md, or its frontmatter, is missing — nothing is written · 2 bad arguments.
"""
import argparse
import os
from pathlib import Path
import sys
import tempfile

# ST-2's fields, in its order; `effort` is the row's first cell.
FIELDS = ["state", "phase", "next", "blocked_on", "gates", "updated", "stream", "lane", "repo_home", "code_home"]

HEADER = (
    "# Register\n"
    "\n"
    "Generated by `scripts/build-register.py` from each effort's `STATUS.md` frontmatter (docs/wow/60 ST-2, ST-4)."
    " Do not edit it: edit STATUS.\n"
    "\n"
    "| effort | " + " | ".join(FIELDS) + " |\n"
    "|" + "---|" * (len(FIELDS) + 1) + "\n"
)


def frontmatter(path):
    """The `key: value` lines between the first two `---` lines of [path], each value as written, a quoted one unquoted."""
    lines = path.read_text(encoding="utf-8").splitlines()
    end = next((at for at, line in enumerate(lines[1:], 1) if line.strip() == "---"), None)
    if not lines or lines[0].strip() != "---" or end is None:
        raise LookupError(f"{path} has no frontmatter between two '---' lines")
    fields = {}
    for line in lines[1:end]:
        if line.startswith((" ", "#")) or ":" not in line:
            continue
        key, _, value = line.partition(":")
        value = value.strip()
        if len(value) >= 2 and value[0] == value[-1] == '"':
            value = value[1:-1]
        fields[key.strip()] = value
    return fields


def cell(text):
    """[text] as one cell of a Markdown table: a pipe escaped, on one line."""
    return text.replace("|", "\\|").replace("\n", " ")


def row(effort, folder, fields):
    status = "STATUS.md" if folder in ("", ".") else f"{folder.strip('/')}/STATUS.md"
    named = fields.get("effort", "")
    rest = named[len(effort):].strip() if named.startswith(effort) else named
    if rest and not rest.startswith("—"):
        rest = "— " + rest
    first = f"[{effort}]({status})" + (f" {rest}" if rest else "")
    return "| " + " | ".join(cell(text) for text in [first] + [fields.get(name, "") for name in FIELDS]) + " |\n"


def main(argv):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--project", required=True, type=Path)
    parser.add_argument("--effort", action="append", default=[], help="NAME=FOLDER, in offices.yaml's order")
    args = parser.parse_args(argv)
    rows = []
    for given in args.effort:
        effort, sep, folder = given.partition("=")
        if not sep or not effort:
            parser.error(f"--effort {given}: NAME=FOLDER")
        status = args.project / folder / "STATUS.md"
        try:
            rows.append(row(effort, folder, frontmatter(status)))
        except (OSError, LookupError) as error:
            print(f"FAIL {effort}: {error}", file=sys.stderr)
            return 1
    text = HEADER + "".join(rows)
    target = args.project / "REGISTER.md"
    # Written whole or not at all: a reader never sees half a register.
    umask = os.umask(0)
    os.umask(umask)
    mode = target.stat().st_mode & 0o777 if target.exists() else 0o666 & ~umask
    with tempfile.NamedTemporaryFile("w", encoding="utf-8", newline="\n", dir=args.project, prefix=".REGISTER-", delete=False) as out:
        out.write(text)
    os.chmod(out.name, mode)
    os.replace(out.name, target)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
